function iso(daysAgo) {
  const d = new Date(Date.now() - daysAgo * 86400000);
  d.setHours(11, 24, 0, 0);
  return d.toISOString();
}

function buildSeed() {
  const now = new Date().toISOString();
  return {
    products: products.map((p) => ({
      ...p,
      createdAt: now,
      active: true,
      featured: p.id === 'p-creamy' || p.id === 'p-protein',
      rating: null, // computed from reviews at render time
      reviewCount: null,
    })),
    reviews,
    coupons: coupons.map((c) => ({ ...c })),
    orders: demoOrders.map((o) => ({ ...o })),
    messages,
    subscribers,
    notifications: demoOrders.slice(0, 3).map((o, i) => ({
      id: `n-0${i + 1}`,
      createdAt: o.createdAt,
      channel: o.payment === 'cod' ? 'whatsapp' : 'email',
      kind: 'order.created',
      to: o.payment === 'cod' ? o.customer.phone : o.customer.email,
      subject: `Order ${o.id} received`,
      body: `Thanks ${o.customer.name.split(' ')[0]}! Your ORGANICHY order ${o.id} is confirmed for ₹${o.total}. We pack within 24 hours on business days.`,
      status: 'queued',
      note: 'Real sending is a 5-line change in lib/notify.js',
    })),
  };
}

